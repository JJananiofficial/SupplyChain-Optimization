"""Authentication and per-user workspace persistence.

Local development uses SQLite and prototype passwords. Hosted deployments can
use Streamlit OIDC with a managed PostgreSQL database.
"""
from __future__ import annotations

from contextlib import contextmanager
import hashlib
import hmac
import json
import os
import secrets
import sqlite3
from pathlib import Path
from typing import Any, Iterator

DEFAULT_DB_PATH = Path(__file__).resolve().parents[1] / "data" / "app_users.db"
DB_PATH = Path(os.getenv("SUPPLYCHAIN_DB_PATH", str(DEFAULT_DB_PATH)))
DATABASE_URL = os.getenv("SUPPLYCHAIN_DATABASE_URL", "").strip() or None
PBKDF2_ITERATIONS = 310_000
PUBLIC_DEPLOYMENT = os.getenv("SUPPLYCHAIN_PUBLIC_MODE", "false").strip().lower() in {"1", "true", "yes", "on"}
ALLOW_SIGNUP = os.getenv("SUPPLYCHAIN_ALLOW_SIGNUP", "true").strip().lower() not in {"0", "false", "no"}
ALLOW_DEMO_LOGIN = os.getenv("SUPPLYCHAIN_ALLOW_DEMO_LOGIN", "true").strip().lower() not in {"0", "false", "no"}


def configure_database(database_url: str | None = None) -> None:
    """Set a managed database URL provided by deployment secrets."""
    global DATABASE_URL
    if database_url:
        DATABASE_URL = database_url.strip()


def configure_public_mode(enabled: bool | None = None) -> None:
    """Apply a deployment's explicit public-mode setting."""
    global PUBLIC_DEPLOYMENT
    if enabled:
        PUBLIC_DEPLOYMENT = True


def get_auth_config() -> dict[str, Any]:
    return {
        "db_path": str(DB_PATH),
        "database_backend": "postgresql" if DATABASE_URL else "sqlite",
        "allow_signup": ALLOW_SIGNUP and not PUBLIC_DEPLOYMENT,
        "allow_demo_login": ALLOW_DEMO_LOGIN and not PUBLIC_DEPLOYMENT and not DATABASE_URL,
        "public_mode": PUBLIC_DEPLOYMENT,
    }


@contextmanager
def _connect() -> Iterator[Any]:
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        with psycopg.connect(DATABASE_URL, row_factory=dict_row) as conn:
            yield conn
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row
        yield conn


def _execute(conn: Any, query: str, params: tuple[Any, ...] = ()) -> Any:
    return conn.execute(query.replace("?", "%s") if DATABASE_URL else query, params)


def _integrity_error_types() -> tuple[type[BaseException], ...]:
    if DATABASE_URL:
        import psycopg

        return (psycopg.IntegrityError,)
    return (sqlite3.IntegrityError,)


def _create_user_tables(conn: Any) -> None:
    if DATABASE_URL:
        _execute(conn, """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                password_salt TEXT NOT NULL,
                oidc_issuer TEXT,
                oidc_subject TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        _execute(conn, """
            CREATE TABLE IF NOT EXISTS user_workspaces (
                user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                workspace_json TEXT NOT NULL,
                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
    else:
        _execute(conn, """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT NOT NULL COLLATE NOCASE UNIQUE,
                email TEXT NOT NULL COLLATE NOCASE UNIQUE,
                password_hash TEXT NOT NULL,
                password_salt TEXT NOT NULL,
                oidc_issuer TEXT,
                oidc_subject TEXT,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        columns = {row["name"] for row in _execute(conn, "PRAGMA table_info(users)").fetchall()}
        for column in ("oidc_issuer", "oidc_subject"):
            if column not in columns:
                _execute(conn, f"ALTER TABLE users ADD COLUMN {column} TEXT")
        _execute(conn, """
            CREATE TABLE IF NOT EXISTS user_workspaces (
                user_id INTEGER PRIMARY KEY,
                workspace_json TEXT NOT NULL,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
            )
        """)
    _execute(conn, "CREATE UNIQUE INDEX IF NOT EXISTS users_oidc_identity_unique ON users(oidc_issuer, oidc_subject)")
    _execute(conn, "CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique ON users(LOWER(username))")
    _execute(conn, "CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users(LOWER(email))")


def _derive(password: str, salt: bytes) -> bytes:
    return hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, PBKDF2_ITERATIONS)


def init_auth_db() -> None:
    """Create auth/workspace schema and a local-only demo account if enabled."""
    with _connect() as conn:
        _create_user_tables(conn)
        if not DATABASE_URL and get_auth_config()["allow_demo_login"]:
            demo = _execute(conn, "SELECT id FROM users WHERE username = ? COLLATE NOCASE", ("planner_demo",)).fetchone()
            if demo is None:
                salt = secrets.token_bytes(16)
                pw_hash = _derive("demo12345", salt)
                _execute(
                    conn,
                    "INSERT INTO users(username,email,password_hash,password_salt) VALUES(?,?,?,?)",
                    ("planner_demo", "demo@supplychain.org", pw_hash.hex(), salt.hex()),
                )


def register_user(username: str, email: str, password: str) -> tuple[bool, str]:
    if not get_auth_config()["allow_signup"]:
        return False, "Self-registration is disabled in this deployment. Use the approved identity provider or contact an administrator."
    username = username.strip()
    email = email.strip().lower()
    if len(username) < 3 or len(username) > 32:
        return False, "Username must contain 3–32 characters."
    if not all(ch.isalnum() or ch in "._-" for ch in username):
        return False, "Username may contain letters, numbers, dots, underscores and hyphens."
    if "@" not in email or len(email) > 254:
        return False, "Enter a valid email address."
    if len(password) < 8:
        return False, "Password must contain at least 8 characters."

    salt = secrets.token_bytes(16)
    password_hash = _derive(password, salt)
    try:
        with _connect() as conn:
            _execute(
                conn,
                "INSERT INTO users(username,email,password_hash,password_salt) VALUES(?,?,?,?)",
                (username, email, password_hash.hex(), salt.hex()),
            )
        return True, "Account created. You can now sign in."
    except _integrity_error_types():
        return False, "That username or email is already registered."


def authenticate_user(identifier: str, password: str) -> dict[str, Any] | None:
    if not identifier or not password:
        return None
    with _connect() as conn:
        row = _execute(
            conn,
            "SELECT id, username, email, password_hash, password_salt "
            "FROM users WHERE LOWER(username)=LOWER(?) OR LOWER(email)=LOWER(?)",
            (identifier.strip(), identifier.strip()),
        ).fetchone()
    if row is None:
        return None
    expected = bytes.fromhex(row["password_hash"])
    actual = _derive(password, bytes.fromhex(row["password_salt"]))
    if not hmac.compare_digest(expected, actual):
        return None
    return {"id": row["id"], "username": row["username"], "email": row["email"]}


def provision_oidc_user(issuer: str, subject: str, email: str | None, display_name: str | None) -> dict[str, Any]:
    """Create or retrieve a local workspace identity for a verified OIDC subject."""
    issuer, subject = issuer.strip(), subject.strip()
    if not issuer or not subject:
        raise ValueError("The identity provider did not return an issuer and subject.")
    stable_id = hashlib.sha256(f"{issuer}\0{subject}".encode("utf-8")).hexdigest()
    username = f"oidc_{stable_id[:40]}"
    normalized_email = (email or "").strip().lower()
    if not normalized_email:
        normalized_email = f"{username}@oidc.invalid"
    if len(normalized_email) > 254:
        raise ValueError("The identity provider returned an invalid email address.")
    salt = secrets.token_bytes(16)
    password_hash = _derive(secrets.token_urlsafe(32), salt)
    try:
        with _connect() as conn:
            _execute(
                conn,
                """INSERT INTO users(username,email,password_hash,password_salt,oidc_issuer,oidc_subject)
                   VALUES(?,?,?,?,?,?)
                   ON CONFLICT(oidc_issuer,oidc_subject) DO UPDATE SET email=excluded.email""",
                (username, normalized_email, password_hash.hex(), salt.hex(), issuer, subject),
            )
            row = _execute(
                conn,
                "SELECT id, email FROM users WHERE oidc_issuer=? AND oidc_subject=?",
                (issuer, subject),
            ).fetchone()
    except _integrity_error_types() as exc:
        raise ValueError("This identity provider account conflicts with an existing workspace account.") from exc
    if row is None:
        raise RuntimeError("The identity provider account could not be provisioned.")
    return {
        "id": row["id"],
        "username": (display_name or "").strip() or normalized_email,
        "email": row["email"],
        "identity_provider": issuer,
    }


def save_workspace(user_id: int, workspace: dict[str, Any]) -> None:
    payload = json.dumps(workspace, ensure_ascii=False, default=str)
    with _connect() as conn:
        _execute(
            conn,
            """INSERT INTO user_workspaces(user_id,workspace_json,updated_at)
               VALUES(?,?,CURRENT_TIMESTAMP)
               ON CONFLICT(user_id) DO UPDATE SET
               workspace_json=excluded.workspace_json,
               updated_at=CURRENT_TIMESTAMP""",
            (user_id, payload),
        )


def load_workspace(user_id: int) -> dict[str, Any] | None:
    with _connect() as conn:
        row = _execute(
            conn,
            "SELECT workspace_json FROM user_workspaces WHERE user_id=?",
            (user_id,),
        ).fetchone()
    if row is None:
        return None
    try:
        return json.loads(row["workspace_json"])
    except (TypeError, json.JSONDecodeError):
        return None
